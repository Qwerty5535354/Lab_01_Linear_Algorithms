# Лабораторна робота №1, варіант 5
# Завдання 1: розділити двоцифрове число на цифри (через пробіл)
# Завдання 2: перевести температуру з Цельсія у Фаренгейти та Кельвіни

import math

# ---------- Завдання 1 ----------
print("Завдання 1")
try:
    num = abs(int(input("Введіть двоцифрове число: ")))  # abs - щоб працювало і для від'ємних
    if 10 <= num <= 99:
        tens = num // 10   # десятки
        units = num % 10   # одиниці
        print(tens, units)
    else:
        print("Помилка: число не є двоцифровим")
except ValueError:
    print("Помилка: потрібно ввести ціле число")

# ---------- Завдання 2 ----------
print("\nЗавдання 2")
try:
    tc = float(input("Введіть температуру в градусах Цельсія: ").replace(",", "."))
    if not math.isfinite(tc):
        print("Помилка: потрібно ввести скінченне число")
    elif tc < -273.15:
        print("Помилка: температура нижча за абсолютний нуль (-273.15)")
    else:
        tf = tc * 1.8 + 32   # Фаренгейт
        tk = tc + 273.15     # Кельвін
        print(f"Фаренгейт: {tf:.2f}")
        print(f"Кельвін: {tk:.2f}")
except ValueError:
    print("Помилка: потрібно ввести число")
